#!/usr/bin/env node
// Scaffold a new app screen that already passes the 390 × 844 check in light and dark.
//
//   node scripts/new-app.mjs <id> "<Name>" <#accent> ["one-line description"] [--num=04] [--force]
//   node scripts/new-app.mjs habit-tracker "Habit Tracker" "#F97316" "Daily habits and streaks"
//
// Creates
//   <id>.html                 the screen (app bar, content, footer, menu sheet, toast) — fill in the content
//   styles/apps/<id>.css      the accent for light + dark (contrast worked out here) and the screen's own styles
//   scripts/apps/<id>.js      the screen's logic: AUKit.defineScreen(<id>, …)
// and adds the app to apps/registry.js (preview list, capture states, 390 × 844 check).
import { readFile, writeFile, mkdir, access } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const flags = Object.fromEntries(args.filter((a) => a.startsWith('--')).map((a) => { const [k, v] = a.slice(2).split('='); return [k, v ?? true]; }));
const [id, name, accentIn, desc = ''] = args.filter((a) => !a.startsWith('--'));

const fail = (msg) => { console.error(`✕ ${msg}\n  usage: node scripts/new-app.mjs <id> "<Name>" <#accent> ["description"] [--num=04] [--force]`); process.exit(1); };
if (!id || !name || !accentIn) fail('id, name and accent are required');
if (!/^[a-z][a-z0-9]*(-[a-z0-9]+)*$/.test(id)) fail(`id "${id}" must be kebab-case (e.g. habit-tracker)`);
const accent = accentIn.startsWith('#') ? accentIn.toUpperCase() : `#${accentIn.toUpperCase()}`;
if (!/^#[0-9A-F]{6}$/.test(accent)) fail(`accent "${accentIn}" must be a 6-digit hex colour`);

/* ---- colour: WCAG contrast, mixing ------------------------------------------------------------------------------------ */
const rgb = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16));
const hex = (c) => `#${c.map((v) => Math.round(Math.min(255, Math.max(0, v))).toString(16).padStart(2, '0')).join('').toUpperCase()}`;
const lin = (v) => { v /= 255; return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4; };
const lum = (h) => { const [r, g, b] = rgb(h).map(lin); return 0.2126 * r + 0.7152 * g + 0.0722 * b; };
const contrast = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
const mix = (a, b, t) => hex(rgb(a).map((v, i) => v + (rgb(b)[i] - v) * t));
const towards = (base, target, against, min) => { for (let t = 0; t <= 1.0001; t += 0.02) { const c = mix(base, target, t); if (against.every((bg) => contrast(c, bg) >= min)) return c; } return target; };

const LIGHT_BG = ['#FFFFFF', '#F6F7F9'];               // screen, card
const DARK_BG = ['#0F1013', '#1A1C21'];
const accentFg = towards(accent, '#000000', LIGHT_BG, 4.6);       // accent text on light surfaces
const accentFgDark = towards(accent, '#FFFFFF', DARK_BG, 4.6);    // … on dark surfaces
const accentWeak = mix(accent, '#FFFFFF', 0.9);
const [r, g, b] = rgb(accent);
const accentWeakDark = `rgba(${r}, ${g}, ${b}, 0.18)`;
const onWhite = contrast(accent, '#FFFFFF'); const onDark = contrast(accent, '#0F1013');
const ctaFg = onWhite >= 4.5 ? '#FFFFFF' : onDark >= 4.5 ? '#0F1013' : (onWhite >= onDark ? '#FFFFFF' : '#0F1013');
const ctaRatio = Math.max(ctaFg === '#FFFFFF' ? onWhite : onDark).toFixed(1);

/* ---- registry: next number, no duplicates ----------------------------------------------------------------------------- */
const regPath = path.join(ROOT, 'apps/registry.js');
let reg = await readFile(regPath, 'utf8');
if (reg.includes(`id: '${id}'`) && !flags.force) fail(`"${id}" is already in apps/registry.js`);
const nums = [...reg.matchAll(/num: '(\d+)(?:\.\d+)?'/g)].map((m) => Number(m[1]));   // "1.3" (scenario screens) counts as 1
const num = String(flags.num || (Math.max(0, ...nums) + 1)).padStart(2, '0');
const prefix = id.split('-').map((w) => w[0]).join('').slice(0, 3);
const exists = async (p) => { try { await access(p); return true; } catch { return false; } };
for (const f of [`${id}.html`, `styles/apps/${id}.css`, `scripts/apps/${id}.js`]) if (await exists(path.join(ROOT, f)) && !flags.force) fail(`${f} exists (use --force to overwrite)`);
const q = (s) => s.replace(/\\/g, '\\\\').replace(/'/g, "\\'");
const h = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

/* ---- files ------------------------------------------------------------------------------------------------------------ */
const css = `/* ${num} ${name} — accent and screen styles. Prefix for this screen's classes: ${prefix}-
   Generated by scripts/new-app.mjs. Text on white ${contrast(accentFg, '#FFFFFF').toFixed(1)}:1 · on dark ${contrast(accentFgDark, '#0F1013').toFixed(1)}:1 · button text ${ctaRatio}:1 */

[data-au-app="${id}"] { --au-accent: ${accent}; --au-accent-fg: ${accentFg}; --au-accent-weak: ${accentWeak}; --au-focus: ${accentFg};
  --au-cta-bg: ${accent}; --au-cta-fg: ${ctaFg}; }
[data-au-theme="dark"] [data-au-app="${id}"] { --au-accent-fg: ${accentFgDark}; --au-accent-weak: ${accentWeakDark}; --au-focus: ${accentFgDark}; }
@media (prefers-color-scheme: dark) {
  :root:not([data-au-theme="light"]) [data-au-app="${id}"] { --au-accent-fg: ${accentFgDark}; --au-accent-weak: ${accentWeakDark}; --au-focus: ${accentFgDark}; }
}

/* ---- ${name} screen — colours only from tokens (var(--au-…)), so both themes work ---------------------------------------- */
.${prefix}-hero { display: flex; flex-direction: column; gap: var(--au-s-1); }
.${prefix}-hero__value { font-size: var(--au-display); line-height: var(--au-display-lh); font-weight: var(--au-weight-bold); letter-spacing: -0.03em; font-variant-numeric: tabular-nums; }
`;

const html = `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <meta name="color-scheme" content="light dark">
  <meta name="theme-color" content="#FFFFFF" media="(prefers-color-scheme: light)">
  <meta name="theme-color" content="#0F1013" media="(prefers-color-scheme: dark)">
  <title>${h(name)}</title>
  <link rel="stylesheet" href="styles/tokens.css">
  <link rel="stylesheet" href="styles/components.css">
  <link rel="stylesheet" href="styles/apps/${id}.css">
  <script>/* before first paint: theme (?theme= → saved choice → OS) and modes (?ui=1 ?capture=1 ?statusbar=1 ?embed=1) */
  (function(){var p=new URLSearchParams(location.search),r=document.documentElement,c=r.classList,t=p.get('theme');
  if(!t&&p.get('capture')!=='1'&&p.get('embed')!=='1'){try{t=localStorage.getItem('au-theme')}catch(e){}}
  if(t==='light'||t==='dark')r.setAttribute('data-au-theme',t);
  var l=p.get('lang');if(!l&&p.get('capture')!=='1'&&p.get('embed')!=='1'){try{l=localStorage.getItem('au-lang')}catch(e){}}if(l==='ko'){r.setAttribute('data-au-lang','ko');r.lang='ko';r.classList.add('au-i18n-pending');setTimeout(function(){r.classList.remove('au-i18n-pending')},1500);}
  if(p.get('ui')==='1')c.add('is-ui-only');if(p.get('capture')==='1')c.add('is-capture');if(p.get('statusbar')==='1')c.add('has-system-bars');if(p.get('embed')==='1')c.add('is-embed');})();</script>
  <script src="scripts/i18n/ko.js" defer></script>
  <script src="scripts/app.js" defer></script>
  <script src="scripts/apps/${id}.js" defer></script>
</head>
<body>
<div class="au-stage">
  <div class="au-screen" id="screen" data-au-app="${id}" data-au-screen="${id}">
    <div class="au-status-bar" aria-hidden="true"><span class="au-num">9:41</span></div>

    <header class="au-app-bar">
      <button class="au-icon-button" type="button" aria-label="Back" data-action="back"><i class="au-icon au-icon--back"></i></button>
      <h1 class="au-app-bar__title">${h(name)}</h1>
      <button class="au-icon-button" type="button" aria-label="More options" aria-haspopup="dialog" aria-controls="${id}-menu" data-action="menu"><i class="au-icon au-icon--more"></i></button>
    </header>

    <main class="au-content" id="content">
      <!-- TODO: the screen's sections, top to bottom. Keep the default state inside 390 × 844 without scrolling. -->
      <section class="au-card ${prefix}-hero" aria-labelledby="${prefix}-hero-title">
        <div class="au-card__head">
          <i class="au-icon au-icon--sparkle" aria-hidden="true"></i>
          <h2 class="au-card__title" id="${prefix}-hero-title">${h(name)}</h2>
          <span class="au-demo-tag">Demo</span>
        </div>
        <p class="${prefix}-hero__value" id="${prefix}-value">0</p>
        <p class="au-text-meta">${h(desc || 'Describe what this number means.')}</p>
      </section>

      <section class="au-section" aria-labelledby="${prefix}-list-title" style="margin-top: var(--au-section-gap)">
        <div class="au-section-head">
          <h2 class="au-section-head__title" id="${prefix}-list-title">Details</h2>
          <span class="au-section-head__meta">Sample</span>
        </div>
        <div class="au-card">
          <dl class="au-rows">
            <div class="au-row"><dt class="au-row__label">Status</dt><dd class="au-row__value" data-tone="positive">Ready</dd></div>
            <div class="au-row"><dt class="au-row__label">Updated</dt><dd class="au-row__value">Just now</dd></div>
          </dl>
        </div>
      </section>
    </main>

    <footer class="au-footer">
      <button class="au-button" type="button" data-action="primary"><span>Primary Action</span></button>
    </footer>

    <div class="au-home-indicator" aria-hidden="true"></div>

    <div class="au-scrim" data-action="close-sheet" hidden></div>
    <section class="au-sheet" id="${id}-menu" role="dialog" aria-modal="true" aria-labelledby="${id}-menu-title" tabindex="-1" hidden>
      <div class="au-sheet__grabber" aria-hidden="true"></div>
      <div class="au-sheet__head">
        <h2 class="au-sheet__title" id="${id}-menu-title">Options</h2>
        <button class="au-icon-button" type="button" aria-label="Close" data-action="close-sheet"><i class="au-icon au-icon--close"></i></button>
      </div>
      <div class="au-sheet__body">
        <div class="au-menu">
          <button class="au-menu__item" type="button" data-action="share"><i class="au-icon au-icon--share"></i>Share</button>
          <button class="au-menu__item" type="button" data-action="reset" data-tone="critical"><i class="au-icon au-icon--reset"></i>Reset demo data</button>
        </div>
      </div>
    </section>

    <div class="au-toast" role="status" aria-live="polite"><div class="au-toast__inner" id="toast"></div></div>
    <p class="au-visually-hidden" aria-live="polite"></p>
  </div>

  <nav class="au-devbar" aria-label="Preview controls">
    <a href="index.html"><i class="au-icon au-icon--back"></i>All screens</a>
    <button type="button" data-dev="theme">Theme: System</button>
    <button type="button" data-dev="lang" translate="no">한국어</button>
    <button type="button" data-dev="system-bars" aria-pressed="false">Status bar</button>
    <button type="button" data-dev="ui-only" aria-pressed="false">UI-only</button>
    <button type="button" data-dev="reset"><i class="au-icon au-icon--reset"></i>Reset</button>
  </nav>
</div>
</body>
</html>
`;

const js = `/* ${num} ${name} — screen logic. Loaded after scripts/app.js (both with defer).
   Buttons with data-action="name" call actions.name(button, event). Built-in actions: back, close-sheet, reset, share.
   ctx: { screen, id, toast, sheets, announce, fog, store, $, $$, esc }
   - store.get('${id}', DEFAULTS) / store.set('${id}', state)   demo data that survives a reload (ignored with ?capture=1)
   - apply(params)   put the screen in a state from the URL (?…) — add each to the app's "states" in apps/registry.js
   - reset()         back to DEFAULTS (preview "Reset", menu "Reset demo data")                                          */
AUKit.defineScreen('${id}', ({ screen, toast, sheets, announce, store, $ }) => {
  const DEFAULTS = { value: 0 };
  let state = store.get('${id}', DEFAULTS);
  const save = () => store.set('${id}', state);

  function render() {
    $('#${prefix}-value').textContent = state.value;
  }

  return {
    actions: {
      menu: (btn) => sheets.open('${id}-menu', btn),
      primary: () => { state.value += 1; save(); render(); toast('Done · demo'); announce(\`Value \${state.value}\`); },
    },
    reset() { state = JSON.parse(JSON.stringify(DEFAULTS)); render(); },
    apply(params) {
      if (params.has('value')) state.value = Number(params.get('value')) || 0;
      render();
      if (params.get('sheet') === 'menu') sheets.open('${id}-menu');
    },
  };
});
`;

const entry = `  {
    id: '${id}', num: '${num}', name: '${q(name)}', desc: '${q(desc)}',
    file: '${id}.html', accent: '${accent}', css: 'styles/apps/${id}.css',
    states: [
      { label: 'Default', q: '' },
      { label: 'Menu open', q: 'sheet=menu' },
    ],
    notes: [
      'TODO: what the default capture shows, and which states are worth capturing.',
    ],
  },
`;

await mkdir(path.join(ROOT, 'styles/apps'), { recursive: true });
await mkdir(path.join(ROOT, 'scripts/apps'), { recursive: true });
await writeFile(path.join(ROOT, `${id}.html`), html);
await writeFile(path.join(ROOT, `styles/apps/${id}.css`), css);
await writeFile(path.join(ROOT, `scripts/apps/${id}.js`), js);
if (!reg.includes(`id: '${id}'`)) {
  const marker = '  // @new-apps';
  if (!reg.includes(marker)) fail('apps/registry.js has no "// @new-apps" line');
  reg = reg.replace(marker, entry + marker);
  await writeFile(regPath, reg);
}

console.log(`✓ ${num} ${name} (${id})
  ${id}.html · styles/apps/${id}.css · scripts/apps/${id}.js · apps/registry.js
  accent ${accent} · text ${accentFg} (light) / ${accentFgDark} (dark) · button text ${ctaFg} (${ctaRatio}:1)
  class prefix: ${prefix}-
  next: fill in the screen, add its states to apps/registry.js, then run the check in index.html (Light and Dark).`);
